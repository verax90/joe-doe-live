import re, sys, urllib.parse, pathlib
src = pathlib.Path(sys.argv[1])
out = pathlib.Path(sys.argv[2])
names = {
 'play':'play','stop':'square','undo':'undo-2','redo':'redo-2','help':'circle-help','close':'x',
 'mark':'star','look':'maximize-2','remove':'trash-2','dice':'dices','cut':'scissors','record':'circle-dot',
 'back':'arrow-left','next':'arrow-right','skip':'skip-forward','in':'arrow-left-to-line','out':'arrow-right-to-line',
 'all':'move-horizontal','code':'code-xml','film':'film','plus':'plus','upload':'upload','search':'search',
 'up':'arrow-up','down':'arrow-down','volume':'volume-2','mute':'volume-x','learn':'graduation-cap','compose':'music','cheats':'book-open','samples':'audio-waveform','sampler':'disc-3','tools':'wrench','midi':'piano','sp':'keyboard-music','remote':'smartphone','mic':'mic','looper':'repeat','backing':'list-music','pump':'activity','vj':'sparkles','video':'film','set':'list-ordered','room':'radio','overlay-panel':'type','drop':'trending-up','frame':'rectangle-vertical','history':'history','save':'save','new':'file-plus','ascii':'binary','scope':'audio-lines','sequencer':'grid-3x3',
 'more':'ellipsis','apply':'refresh-cw','pause':'pause','layers':'layers','headphones':'headphones','check':'check','copy':'copy','download':'download',
}
lines = ['/* Icons: Lucide (lucide.dev, ISC licence), drawn as CSS masks so they take',
 '   the text colour and survive the language switch rewriting a label.',
 '   Generated by scripts/icons.py from lucide-static 0.460.0: add a name there. */',
 '[data-icon]:not([hidden]) {',
 '  display: inline-flex;',
 '  align-items: center;',
 '  justify-content: center;',
 '  gap: 0.45em;',
 '}','',
 '[data-icon]::before {',
 '  content: "";',
 '  display: inline-block;',
 '  flex: none;',
 '  width: 1.15em;',
 '  height: 1.15em;',
 '  background: currentColor;',
 '  -webkit-mask: var(--icon) center / contain no-repeat;',
 '  mask: var(--icon) center / contain no-repeat;',
 '}','',
 '/* data-icon-end: the icon after the label (Next →) */',
 '[data-icon-end]:not([hidden]) {',
 '  display: inline-flex;',
 '  align-items: center;',
 '  justify-content: center;',
 '  gap: 0.45em;',
 '}','',
 '[data-icon-end]::after {',
 '  content: "";',
 '  width: 1.15em;',
 '  height: 1.15em;',
 '  flex: none;',
 '  background: currentColor;',
 '  -webkit-mask: var(--icon) center / contain no-repeat;',
 '  mask: var(--icon) center / contain no-repeat;',
 '}','']
for key, file in names.items():
    svg = (src / f'{file}.svg').read_text()
    svg = re.sub(r'<!--.*?-->', '', svg, flags=re.S)
    svg = re.sub(r'\s*class="[^"]*"', '', svg)
    svg = re.sub(r'\s+', ' ', svg).replace('> <', '><').strip()
    svg = svg.replace('stroke="currentColor"', 'stroke="black"')
    data = urllib.parse.quote(svg.replace('"', "'"), safe=" =:/.-,'")
    lines.append(f'[data-icon="{key}"],\n[data-icon-end="{key}"] {{\n  --icon: url("data:image/svg+xml,{data}");\n}}\n')
out.write_text('\n'.join(lines))
